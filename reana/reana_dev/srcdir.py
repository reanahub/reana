"""Manage independent REANA source directories.

A source directory is a complete, independent copy of the REANA repository
collection.  Managed source directories are flat and may be named according to
their purpose, for example ``auth-audit``, ``broker-backoff``,
``condor-creds``, or ``dask-dashboard``.  Kitty and Tmux resolve session
targets by prefix, so srcdir names that differ early are quicker to switch
between.

The baseline is the canonical source directory.  Each managed copy is a
``srcdir``; several copies are ``srcdirs``.  A shell, Kitty session, or Tmux
session is merely an optional way to work in a srcdir, not part of its
identity.

The managed root defaults to a sibling of the canonical source directory and
subsequent commands discover it from marker files::

    reana-dev srcdir-create auth-audit
    reana-dev srcdir-workon auth-audit
    reana-dev srcdir-list
    reana-dev srcdir-rename auth-audit auth-api
    reana-dev srcdir-delete auth-api

Creation always copies the canonical source collection, removes copied local
branches, and resets each repository to its already-fetched ``master``
reference.  Remote-tracking references remain available, so branches and PRs
can then be composed with the existing ``git-checkout`` and
``git-checkout-pr`` commands.  Run ``reana-dev git-submodule --update`` after
composing branches so that ignored shared-module copies match them.
Creation uses copy-on-write when supported and a full archival copy otherwise.
Inside Kitty or Tmux, ``srcdir-workon`` uses a dedicated session named after
the srcdir.  Tmux takes precedence when both environments are present.  In
other terminals, it opens a shell in the current terminal.  Pass ``--kitty``,
``--tmux``, or ``--plain`` to override this auto-detection; ``--no-kitty``
and ``--no-tmux`` remain aliases for ``--plain``.  Kitty sessions are
generated as ``<name>.kitty-session`` under
``$XDG_DATA_HOME/kitty/sessions`` (or ``~/.local/share/kitty/sessions``),
renamed with the srcdir, and removed when it is deleted.  Only files carrying
the reana-dev ownership header are ever changed.
"""

